#!/usr/bin/env node
// scripts/gen-version.mjs — writes src/model/version.ts from package.json#claudeCodeVersion and #version (DESIGN.md §7).
// One source of truth for SUPPORTED_CLAUDE_VERSION. Run before `tsc` (the `build` script does).
//   node scripts/gen-version.mjs           write the file (no-op when unchanged)
//   node scripts/gen-version.mjs --check   exit 1 when the committed file is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'model', 'version.ts');

/** @param {string} label @param {unknown} v */
function requireSemver(label, v) {
  if (typeof v !== 'string' || !/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(v)) {
    throw new Error(`gen-version: package.json#${label} must be an exact semver string, got ${JSON.stringify(v)}`);
  }
  return v;
}

export function renderVersionFile(pkg) {
  const claude = requireSemver('claudeCodeVersion', pkg.claudeCodeVersion);
  const lib = requireSemver('version', pkg.version);
  return [
    '// GENERATED by scripts/gen-version.mjs from package.json — do not edit.',
    `export const SUPPORTED_CLAUDE_VERSION = '${claude}' as const;`,
    `export const LIB_VERSION = '${lib}' as const;`,
    '',
  ].join('\n');
}

function main() {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
  const want = renderVersionFile(pkg);
  const have = existsSync(target) ? readFileSync(target, 'utf8') : undefined;
  if (process.argv.includes('--check')) {
    if (have !== want) {
      process.stderr.write('gen-version: src/model/version.ts is stale; run `pnpm gen-version`\n');
      process.exit(1);
    }
    return;
  }
  if (have !== want) writeFileSync(target, want);
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) main();
